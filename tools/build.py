#!/usr/bin/env python3
"""Build the one-file distribution from reviewed, locally vendored sources."""
import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]


def rendered():
    common = (ROOT / "vendor" / "common.py").read_text(encoding="utf-8")
    source = (ROOT / "src" / "checker.py").read_text(encoding="utf-8")
    rules = json.loads((ROOT / "rules" / "snapshot.json").read_text(encoding="utf-8"))
    source_digest = hashlib.sha256(common.encode("utf-8")).hexdigest()
    header = (
        "#!/usr/bin/env python3\n"
        "# SPDX-License-Identifier: AGPL-3.0-only OR LicenseRef-CompleteTech-Commercial\n"
        "# Copyright (c) 2026 CompleteTech LLC. See LICENSING.md.\n"
        "# Generated by tools/build.py. Edit src/checker.py and vendor/common.py.\n"
        "# Vendored common.py SHA-256: " + source_digest + "\n"
        "from __future__ import annotations\n\n"
    )
    common = common.replace("from __future__ import annotations\n", "")
    return header + common.rstrip() + "\n\nRULE_SNAPSHOT = " + repr(rules) + "\n\n" + source.rstrip() + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "next_cache_rce_check.py"
    expected = rendered()
    checksum_path = ROOT / "SHA256SUMS"
    checksums = hashlib.sha256(expected.encode("utf-8")).hexdigest() + "  next_cache_rce_check.py\n"
    checksums += hashlib.sha256((ROOT / "rules" / "snapshot.json").read_bytes()).hexdigest() + "  rules/snapshot.json\n"
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != expected:
            print("Generated checker is stale; run python tools/build.py.", file=sys.stderr)
            return 1
        if not checksum_path.exists() or checksum_path.read_text(encoding="utf-8") != checksums:
            print("Distribution checksums are stale; run python tools/build.py.", file=sys.stderr)
            return 1
        return 0
    target.write_text(expected, encoding="utf-8", newline="\n")
    checksum_path.write_text(checksums, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
